ORDER = ["한식", "중식", "일식", "양식", "분식", "패스트푸드", "아시안"]


def build(rows: list[dict]) -> dict[str, list[str]]:
    menus = {c: list(BASE[c]) for c in ORDER}
    seen = {name for names in menus.values() for name in names}
    present = {r["foodLv4Nm"] for r in rows}
    for lv4, (rename, cat) in FROM_DATA.items():
        if lv4 not in present:
            continue
        name = rename or lv4
        if name in seen:          # 이미 다른 종류에 있으면(피자·카레 등) 처음 자리를 지킨다
            continue
        menus[cat].append(name)
        seen.add(name)
    return menus


def main():
    rows = json.loads((ROOT / "data" / "foods-raw.json").read_text(encoding="utf-8"))
    menus = build(rows)
    body = ",\n".join(f'    "{c}": {json.dumps(menus[c], ensure_ascii=False)}' for c in ORDER)
    block = "  const MENUS = {\n" + body + ",\n  };"
    page = PAGE.read_text(encoding="utf-8")
    new, n = re.subn(r"  const MENUS = \{.*?\n  \};", lambda _: block, page, count=1, flags=re.S)
    assert n == 1, "페이지에서 MENUS를 찾지 못함"
    PAGE.write_text(new, encoding="utf-8", newline="\n")
    print({c: len(menus[c]) for c in ORDER}, "합계", sum(len(v) for v in menus.values()))


if __name__ == "__main__":
    main()
